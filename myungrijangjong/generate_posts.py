# ─── 유틸리티 ──────────────────────────────────────────────
def rand_date(start_year=2015, end_year=2025):
    start = date(start_year, 1, 1)
    end = date(end_year, 12, 31)
    delta = (end - start).days
    return (start + timedelta(days=random.randint(0, delta))).isoformat()

def rand_case_date(case_year):
    start = date(case_year, 1, 1)
    end = date(case_year, 12, 31)
    delta = (end - start).days
    return (start + timedelta(days=random.randint(0, delta))).isoformat()

def rand_tags(*pools, n=3):
    combined = []
    for pool in pools:
        combined.extend(pool)
    return random.sample(combined, min(n, len(combined)))

def write_md(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)

def frontmatter(title, date_str, category, tags, excerpt, author="명리정종", extra=""):
    tags_yml = ", ".join([f'"{t}"' for t in tags])
    base = f"""---
title: "{title}"
date: "{date_str}"
category: "{category}"
tags: [{tags_yml}]
excerpt: "{excerpt}"
author: "{author}"
"""
    if extra:
        base += extra + "\n"
    base += "---\n\n"
    return base


