def _josa_ro(word):
    """단어 끝 글자에 따라 '으로' 또는 '로' 반환."""
    if not word:
        return "로"
    code = ord(word[-1]) - 0xAC00
    if code < 0 or code > 11171:
        return "로"
    jongseong = code % 28
    return "로" if jongseong in (0, 8) else "으로"


