ADVICE_SECTION  = re.compile(r'## 처방 및 조언\n(.*?)(?=\n## |\Z)', re.DOTALL)
FOLLOWUP_BLOCK  = re.compile(
    r'(## 실제 결과 / 후일담\n\n\d{4}년, [가-힣]+씨로부터 소식이 왔다\. [^\n]+\n\n)'
    r'(당시 명식에서.*?)\n\n(---)',
    re.DOTALL
)
CONSULT_TYPE_FM = re.compile(r'^consultType:\s*"?([^"\n]+)"?$', re.MULTILINE)

UNIVERSAL_ITEM1 = re.compile(
    r'1\. \*\*지금은 수성\(守成\)의 때\*\*:.*?\n\n', re.DOTALL)


def make_advice(consult_type: str, next_daewoon: str) -> str:
    pool = ADVICE_POOLS.get(consult_type, ADVICE_POOLS["사업·재물"])
    chosen = random.sample(pool, min(4, len(pool)))

    items = []
    for i, (title, body) in enumerate(chosen, 1):
        items.append(f"{i}. **{title}**: {body}")

    # 마지막 항목: 대운 조언 (모든 유형 공통, 개인화)
    items.append(
        f"{len(items)+1}. **{next_daewoon} 대운, 놓치지 마라**: "
        f"이 대운이 본격화되면 용신이 힘을 얻는다. "
        f"지금의 어려움은 그 도약을 위한 준비 과정임을 잊지 마라."
    )

    return "## 처방 및 조언\n\n" + "\n\n".join(items) + "\n"


def fix_followup(content: str, consult_type: str, surename: str) -> str:
    endings = FOLLOWUP_ENDINGS.get(consult_type, FOLLOWUP_ENDINGS["default"])
    new_ending = random.choice(endings)

    def replace_block(m):
        return m.group(1) + new_ending + "\n\n" + m.group(3)

    return FOLLOWUP_BLOCK.sub(replace_block, content)


# ── next_daewoon 추출 (기존 텍스트에서) ─────────────────────
DAEWOON_RE = re.compile(r'\*\*([甲乙丙丁戊己庚辛壬癸][子丑寅卯辰巳午未申酉戌亥]) 대운에')


fixed = skipped = errors = 0
files = sorted(glob.glob(os.path.join(CONTENT_DIR, "*.md")))

for fp in files:
    try:
        with open(fp, encoding="utf-8") as f:
            content = f.read()

        ct_m = CONSULT_TYPE_FM.search(content)
        if not ct_m:
            skipped += 1
            continue
        consult_type = ct_m.group(1).strip()

        dw_m = DAEWOON_RE.search(content)
        next_dw = dw_m.group(1) if dw_m else "다음"

        # 처방 섹션 교체
        new_advice = make_advice(consult_type, next_dw)
        new_content = ADVICE_SECTION.sub(
            lambda m, na=new_advice: na,
            content
        )

        # 후일담 마무리 교체
        surename_m = re.search(r'([가-힣]{1,2})씨로부터', new_content)
        surename = surename_m.group(1) if surename_m else "의뢰인"
        new_content = fix_followup(new_content, consult_type, surename)

        if new_content != content:
            with open(fp, "w", encoding="utf-8") as f:
                f.write(new_content)
            fixed += 1
        else:
            skipped += 1

    except Exception as e:
        errors += 1

print(f"완료: 수정 {fixed}개 / 변경없음 {skipped}개 / 오류 {errors}개")

